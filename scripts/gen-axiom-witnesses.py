#!/usr/bin/env python3
"""Generate EvmAsm/Progress/AxiomWitnesses.lean (GH #10601, GH #11042).

The module carries one `#print axioms` line per witness abbrev referenced from
a kernel-checked progress registry, so the axiom gate
(`scripts/check-axioms.sh`) can run under `lake build` instead of a
`lake env lean` scratch file: under the lake artifact cache, cache-satisfied
modules have no materialized `.olean` on disk and `lake env lean` cannot
resolve them (issue #10601, in the #10537 family).

Two registries are scanned (GH #11042):

  * `EvmAsm/Progress.lean`          — the `OpcodeEntry` registry (EVM opcodes)
  * `EvmAsm/Progress/Routines.lean` — the `RoutineEntry` registry (verified
                                      guest routines: `rlp_encode_uint_be`,
                                      `rlp_item_size`, the RLP walk chain, …)

⚠️ The name pattern is deliberately namespace-agnostic (`@EvmAsm.<anything>`).
It used to be `@EvmAsm\\.(?:Evm64|Stateless)…`, which matched **nothing** for
the guest surface: `reub_spec_within` is
`EvmAsm.Codegen.RlpEncodeUintBeSAsm.reub_spec_within`, and 289 modules live
under `EvmAsm.Rv64.*`. A witness abbrev outside those two namespaces was
silently dropped, so the gate stayed green while covering nothing — which is
worse than an honest absence, because "covered by CI" is the kind of
assumption nobody re-checks.

⭐ Hence the cross-check in `check_refs`: every theorem a registry row *names*
must have a matching witness abbrev in the same file. A row without one is a
row the axiom gate cannot see, and this script now fails loudly instead of
emitting a quietly-incomplete module. (That check found MCOPY: registered
`.proven` since the registry was introduced, theorem present, abbrev absent.)

Usage:
  python3 scripts/gen-axiom-witnesses.py           # print module to stdout
  python3 scripts/gen-axiom-witnesses.py --write   # overwrite the module

The gate regenerates to a temp file and diffs, so a stale module fails CI.
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROGRESS = ROOT / "EvmAsm" / "Progress.lean"
ROUTINES = ROOT / "EvmAsm" / "Progress" / "Routines.lean"
CORRESPOND = ROOT / "EvmAsm" / "Progress" / "Correspondence.lean"
WITNESS = ROOT / "EvmAsm" / "Progress" / "AxiomWitnesses.lean"

# Registry sources: (path, module to import, strict).
#
# `strict` controls the row cross-check, NOT whether the file is scanned — every
# source's abbrevs reach the gate either way.
#
#   * strict=True  — a row naming a theorem with no witness abbrev in ANY
#     scanned registry is an error.
#   * strict=False — the shortfall is COUNTED AND PRINTED instead.
#
# All three sources are now strict (#11289). Correspondence.lean was
# temporarily non-strict when introduced (#11278): its `spec := some "…"` rows
# named 7 theorems no registry witnessed, whose modules it does not import, and
# #11276 was in flight in the neighbouring file. #11289 registered those 7 as
# `RoutineEntry` rows in Routines.lean (which does import their modules), so the
# cross-check — run against the UNION of all registries below — now finds a
# witness for every Correspondence row. Flipping this to strict is what stops
# the defect class recurring: a future Correspondence row naming an unwitnessed
# theorem is a build error, not a printed note nobody reads.
SOURCES = [
    (PROGRESS, "EvmAsm.Progress", True),
    (ROUTINES, "EvmAsm.Progress.Routines", True),
    (CORRESPOND, "EvmAsm.Progress.Correspondence", True),
]

# Any `EvmAsm.*` witness abbrev target, in any namespace.  Narrowing the
# namespace is what caused the guest surface to be silently uncovered — see the
# module docstring.
#
# Anchored on the abbrev's `:=` rather than matching bare `@EvmAsm.…` anywhere:
# these registries discuss witness names in their own docstrings, and a prose
# mention would otherwise be emitted as a `#print axioms` line for a
# nonexistent declaration (an `@EvmAsm.Codegen.…` in prose yielded a stray
# `#print axioms EvmAsm.Codegen.`).  The `:=` also encodes the actual
# requirement: what puts a theorem in the gate is being *bound* by an abbrev.
NAME_RE = re.compile(r":=\s*(@EvmAsm\.[A-Za-z0-9_.']+)")

# A theorem named by a registry row: `(some "…")` for the positional
# `proofRef`, and `<field> := some "…"` for `coverRef` / named-argument forms.
REF_RE = re.compile(r'some "([A-Za-z0-9_.\']+)"')

HEADER = """\
/-
  Axiom witnesses for `scripts/check-axioms.sh` (GH #10601, GH #11042).

  GENERATED by `scripts/gen-axiom-witnesses.py` from the witness abbrevs
  referenced in `EvmAsm/Progress.lean` (the `OpcodeEntry` registry) and
  `EvmAsm/Progress/Routines.lean` (the `RoutineEntry` registry of verified
  guest routines) — do not edit by hand; regenerate with
  `python3 scripts/gen-axiom-witnesses.py --write`.  The gate regenerates and
  diffs, so a stale file fails CI.

  This module exists so the axiom gate runs under `lake build` instead of
  a `lake env lean` scratch file: under the lake artifact cache,
  cache-satisfied modules have no materialized `.olean` on disk and
  `lake env lean` cannot resolve them (issue #10601, in the #10537
  family).  Building this module prints one `#print axioms` report per
  registry witness into the build log; lake replays messages on
  repeat (fully cached) builds, so the gate stays meaningful in cache
  mode and pays zero re-elaboration.

  Coverage note (#11042): the guest-routine half is a **partial** enumeration
  of the verified guest surface, not a complete one.  `EvmAsm/**` carries on
  the order of 1800 distinct `*_spec_within` names, most of them block-level
  rather than whole-routine, so populating every one is not a single change.
  What is registered is witnessed; what is not registered is still outside the
  gate.  Stated here rather than left implicit, because the assumption this
  file exists to break is "covered by CI".  #11290 tracks turning that residual
  into a measured coverage number rather than prose.  As of #11289 all three
  registries are strict, so within a *registered* file an unwitnessed row is a
  build error — the gap is only in what has not been registered yet.
-/
"""


def witness_names(text: str) -> list[str]:
    """Witness abbrev targets bound in one registry source."""
    names = {n.lstrip("@") for n in NAME_RE.findall(text)}
    # A trailing dot means the match ran into prose, not a real declaration.
    # Refuse rather than emit a `#print axioms` line that cannot resolve.
    malformed = sorted(n for n in names if n.endswith(".") or ".." in n)
    if malformed:
        sys.exit(
            "malformed witness name(s) — these cannot be declarations:\n"
            + "".join(f"    {m}\n" for m in malformed)
        )
    return sorted(names)


def check_refs(path: Path, text: str, names: list[str]) -> list[str]:
    """Registry rows naming a theorem with no matching witness abbrev.

    A `proofRef` is written unqualified or partly qualified (`"ADD…"`,
    `"Env.evm_address_stack_spec_within"`) while the abbrev target is fully
    qualified, so the match is on dotted suffix.
    """
    refs = sorted(set(REF_RE.findall(text)))
    return [
        r for r in refs
        if not any(n == r or n.endswith("." + r) for n in names)
    ]


def collect() -> list[str]:
    """Union of witness names across registries, with the row cross-check."""
    # Pass 1: every witness name across all registries.  The cross-check below
    # runs against this UNION, not per-file: what determines whether a theorem
    # is audited is that *some* scanned registry binds it, not which one.
    # (`rlp_item_size_spec_within` is named by a Correspondence row and
    # witnessed from Routines.lean — reporting that as uncovered would be a
    # false alarm.)
    sources: list[tuple[Path, str, bool, str]] = []
    all_names: list[str] = []
    for path, module, strict in SOURCES:
        if not path.exists():
            sys.exit(f"missing registry source: {path.relative_to(ROOT)}")
        text = path.read_text()
        names = witness_names(text)
        if not names:
            sys.exit(f"no witness abbrevs found in {path.relative_to(ROOT)}")
        sources.append((path, module, strict, text))
        all_names.extend(names)

    # Pass 2: cross-check each registry's rows against the union.
    problems: list[str] = []
    for path, _module, strict, text in sources:
        missing = check_refs(path, text, all_names)
        if not missing:
            continue
        rel = path.relative_to(ROOT)
        if strict:
            problems.append(
                f"{rel}: {len(missing)} registry row(s) name a theorem with no "
                f"witness abbrev in ANY scanned registry, so the axiom gate "
                f"cannot see them:\n"
                + "".join(f"    {m}\n" for m in missing)
            )
        else:
            # Declared residual — stderr, so it surfaces on every run without
            # perturbing the stdout module the gate diffs.
            print(
                f"note: {rel}: {len(missing)} row(s) name a theorem that no "
                f"scanned registry witnesses, so those are NOT audited: "
                + ", ".join(missing),
                file=sys.stderr,
            )
    if problems:
        sys.exit(
            "\n".join(problems)
            + "\nAdd a `private noncomputable abbrev _<name>_witness := "
            "@EvmAsm.…` for each, or drop the row.\n"
            "(Naming a theorem in a registry row does NOT put it in the gate — "
            "the abbrev is what does.)"
        )
    return sorted(set(all_names))


def render(names: list[str]) -> str:
    imports = "".join(f"import {module}\n" for _path, module, _s in SOURCES)
    body = "".join(f"\n#print axioms {n}\n" for n in names)
    return HEADER + imports + body


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true",
                    help=f"overwrite {WITNESS.relative_to(ROOT)}")
    args = ap.parse_args()
    names = collect()
    text = render(names)
    if args.write:
        WITNESS.write_text(text)
        print(f"wrote {WITNESS.relative_to(ROOT)} "
              f"({len(names)} witnesses)")
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
